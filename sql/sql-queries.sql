-- =============================================================================
-- Индекс SQL-проверок после прогона API-автотестов
--
-- Автотесты проверяют HTTP-контракт. SQL проверяет вторую половину системы -
-- что сервисы записали в БД. Нужен для дефектов, где ответ выглядит корректно,
-- а состояние данных - нет (каскадные удаления, осиротевшие записи, права).
--
-- БАЗЫ ИЗОЛИРОВАНЫ. users_db, projects_db и observations_db - три отдельных
-- сервера Postgres, поэтому внешних ключей между ними нет вообще:
--
--   participations.project_id  -> projects.id          (FK отсутствует)
--   projects.user_id           -> users.id             (FK отсутствует)
--   observations.user_id       -> users.id             (FK отсутствует)
--   observations.mission_id    -> missions.id          (FK отсутствует)
--
-- Следствие: подделанный или удалённый на одной стороне идентификатор НЕ
-- приведёт к ошибке при вставке. Проверки U7, P4 и O1 существуют именно
-- поэтому - их приходится делать вручную, сверяя вывод разных баз.
--
-- -- Как запускать ------------------------------------------------------------
-- Файл разбит по базам: у каждой свой набор таблиц, поэтому один файл нельзя
-- скормить всем трём базам подряд - на чужой таблице будет ошибка. Файлы надо
-- передать каждой базе отдельно:
--
--   ./stand/up.sh backend                        # поднять стенд и применить seed
--   ./api/newman.sh                              # прогнать автотесты
--   ./stand/up.sh psql users_db        < sql/00-users-db.sql
--   ./stand/up.sh psql projects_db     < sql/10-projects-db.sql
--   ./stand/up.sh psql observations_db < sql/20-observations-db.sql
--
-- ВНИМАНИЕ: блок O4 в observations_db удаляет данные. Он идёт последним и нужен
-- только после прогона автотестов - иначе стенд останется без наблюдения.
-- =============================================================================


-- -- Состав проверок ----------------------------------------------------------
--
-- | Файл                    | ID         | Что проверяет                        |
-- |-------------------------|------------|--------------------------------------|
-- | 00-users-db.sql         | U1...U7      | seed, роли, хеши, CHECK, участия     |
-- | 10-projects-db.sql      | P1...P6      | миграция тегов, уникальность, задания|
-- | 20-observations-db.sql  | O1...O9 (+b) | ссылки, комментарии, object_key, каскад|
--
-- 25 уникальных ID при 26 SQL-операторах. Лишний оператор - у [O4]: DELETE плюс
-- SELECT-подтверждение. Остальные, включая [O5b], [O6b] и [O8b], - это один
-- SELECT со вложенным COUNT.
--
-- Инварианты и их привязка к дефектам - в docs/traceability-sql.md.


-- -- Сессии: Redis, а не Postgres ---------------------------------------------
--
-- Проверяется вручную:
--   docker compose exec redis redis-cli --scan --pattern 'sess:*' | head
-- После выхода из аккаунта ключ его сессии должен исчезнуть, иначе токен
-- продолжает работать (см. баг-репорты по разлогину).


-- -- Чего SQL не может проверить ----------------------------------------------
--
--   - коды ответов и заголовки - только Newman
--   - поведение CORS и preflight - только Newman (папка 10 Contract)
--   - сессии - Redis, не Postgres
--   - содержимое файлов в MinIO - в object_key нет расширения ([O6b])
--   - обход пароля на 72 байтах - нужен второй запрос со сменой хеша,
--     см. открытые вопросы в api/api-testing-conventions.md